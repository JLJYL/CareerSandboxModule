"""技能補強的兩組 prompt（成員 A）。

1. 課程技能抽取（離線 build_resources 用）：從課程大綱抽「修完會具備的技能」。
2. 資源說明句 note（線上 reinforce 用）：對一筆資源寫一句為什麼能補該技能。

鐵律：抽取不要求模型用詞彙表名稱（會硬湊），抽完交正規化器對；
note 禁驚嘆號、去 AI 味，數字與評價詞不得超出資源原文（機械防線在 reinforce.py）。
"""

# ---------------------------------------------------------------------------
# 一、課程技能抽取（build_resources.py 第一段）
# ---------------------------------------------------------------------------

EXTRACT_SYSTEM_PROMPT = """你是課程分析助手。根據課程名稱與課程大綱，列出「修完這門課會具備的能力與技能」。

規則：
1. 只抽「修完會具備的技能」，不要抽先修條件、不要抽課程主題名詞本身。
2. 用自然、常見的技能說法即可，不必套用任何標準詞表。
3. 一門課抽 3 到 8 個技能標籤，太籠統（如「學習能力」）不要。
4. 只輸出 JSON：{"skills": ["技能1", "技能2", ...]}，不要多餘文字。"""


def build_extract_prompt(title: str, outline: str) -> str:
    outline = (outline or "")[:1200]
    return f"課程名稱：{title}\n課程大綱：{outline}\n\n請列出修完這門課會具備的技能。"


# ---------------------------------------------------------------------------
# 二、資源說明句 note（reinforce.py 線上生成，整批一次）
# ---------------------------------------------------------------------------

NOTE_SYSTEM_PROMPT = """你是職涯輔導助手。使用者缺某項技能，以下每筆是一個可補該技能的課程或競賽。
為每一筆寫「一句話」說明它為什麼能補上對應技能，像真人顧問說話，自然、具體。

規則：
1. 一筆一句，20 到 45 字，直述句。
2. 只根據提供的 title 與 description，不要加入原文沒有的數字或誇飾詞（成功、精通、大幅等）。
3. 禁止驚嘆號，不要樣板腔（致力於、豐富的經驗）。
4. 嚴格按輸入順序輸出，只回 JSON：{"notes": ["第1筆的說明", "第2筆的說明", ...]}，筆數與輸入相同。"""

NOTE_RETRY_SUFFIX = ("\n\n上一版有筆數不符或出現原文沒有的數字／誇飾詞。"
                     "請重寫，嚴格只用各筆 description 的內容，筆數與順序與輸入一致。")


def build_note_prompt(pairs: list[tuple]) -> str:
    """pairs: [(skill, resource_dict), ...]。輸出逐筆列出要補的技能與資源原文。"""
    lines = []
    for i, (skill, r) in enumerate(pairs, 1):
        desc = (r.get("description", "") or "")[:300]
        lines.append(f"[{i}] 要補的技能：{skill}\n    名稱：{r.get('title', '')}\n"
                     f"    說明：{desc}")
    return "共 " + str(len(pairs)) + " 筆，請逐筆各寫一句：\n\n" + "\n\n".join(lines)
